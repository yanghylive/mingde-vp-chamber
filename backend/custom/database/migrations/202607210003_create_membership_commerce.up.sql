  `add_time` int(10) UNSIGNED NOT NULL DEFAULT '0' COMMENT '发生时间',
  PRIMARY KEY (`id`) USING BTREE,
  UNIQUE KEY `uk_membership_effect_key` (`tenant_id`,`effect_key`) USING BTREE,
