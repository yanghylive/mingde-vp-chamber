CREATE TABLE IF NOT EXISTS `ch_membership_term_effect` (
  `id` bigint(20) UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '会籍期限变更效果ID',
  `tenant_id` int(10) UNSIGNED NOT NULL DEFAULT '0' COMMENT '租户ID',
  `term_id` bigint(20) UNSIGNED NOT NULL DEFAULT '0' COMMENT 'ch_membership_term.id',
  `order_context_id` bigint(20) UNSIGNED NOT NULL DEFAULT '0' COMMENT 'ch_order_context.id',
  `effect_key` char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '稳定幂等键SHA-256',
  `effect_hash` char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '规范化效果载荷SHA-256',
  `event_id` char(64) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '来源商业事件ID，人工操作可为NULL',
  `completion_id` varchar(128) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '退款完成证据ID，非退款可为NULL',
  `effect_type` varchar(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'grant/full_refund/adjustment等',
  `refund_delta` decimal(16,2) UNSIGNED NOT NULL DEFAULT '0.00' COMMENT '本次可信退款增量',
  `before_state` tinyint(1) UNSIGNED NOT NULL DEFAULT '0' COMMENT '变更前事实状态，0为无记录',
  `after_state` tinyint(1) UNSIGNED NOT NULL DEFAULT '0' COMMENT '变更后事实状态',
  `before_end_time` int(10) UNSIGNED NOT NULL DEFAULT '0' COMMENT '变更前结束时间',
  `after_end_time` int(10) UNSIGNED NOT NULL DEFAULT '0' COMMENT '变更后结束时间',
  `reason_code` varchar(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT '' COMMENT '稳定原因码',
  `operator_type` tinyint(1) UNSIGNED NOT NULL DEFAULT '0' COMMENT '0系统，1用户，2管理员',
