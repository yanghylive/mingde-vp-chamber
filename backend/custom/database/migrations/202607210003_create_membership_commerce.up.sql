SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS `ch_membership_plan` (
  `id` int(10) UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '会籍计划ID',
  `tenant_id` int(10) UNSIGNED NOT NULL DEFAULT '0' COMMENT '租户ID',
  `channel_id` int(10) UNSIGNED NOT NULL DEFAULT '0' COMMENT '渠道ID，必须显式指定',
  `plan_code` varchar(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '租户渠道内稳定计划编码',
  `name` varchar(80) NOT NULL DEFAULT '' COMMENT '计划展示名称',
  `tier` tinyint(1) UNSIGNED NOT NULL DEFAULT '3' COMMENT '会籍等级：3=L3，4=L4',
  `purchase_enabled` tinyint(1) UNSIGNED NOT NULL DEFAULT '0' COMMENT '是否允许购买：0否，1是',
  `price` decimal(16,2) UNSIGNED NOT NULL DEFAULT '0.00' COMMENT '计划价格',
  `currency` char(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'CNY' COMMENT 'ISO 4217币种',
  `term_months` smallint(5) UNSIGNED NOT NULL DEFAULT '12' COMMENT '每次购买增加月数',
  `product_id` int(10) UNSIGNED NOT NULL DEFAULT '0' COMMENT 'CRMEB eb_store_product.id',
  `product_attr_unique` varchar(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT '' COMMENT 'CRMEB规格唯一值',
  `benefits_json` longtext NOT NULL COMMENT '权益配置JSON',
  `renewal_policy_json` longtext NOT NULL COMMENT '续费规则JSON',
  `upgrade_policy_json` longtext NOT NULL COMMENT '升级规则JSON',
  `refund_policy_json` longtext NOT NULL COMMENT '退款规则JSON',
  `config_version` int(10) UNSIGNED NOT NULL DEFAULT '1' COMMENT '配置版本',
  `status` tinyint(1) UNSIGNED NOT NULL DEFAULT '0' COMMENT '状态：0草稿，1启用，2停用，3归档',
  `effective_time` int(10) UNSIGNED NOT NULL DEFAULT '0' COMMENT '配置生效时间',
  `end_time` int(10) UNSIGNED NOT NULL DEFAULT '0' COMMENT '配置失效时间，0为未计划',
  `add_time` int(10) UNSIGNED NOT NULL DEFAULT '0' COMMENT '创建时间',
  `update_time` int(10) UNSIGNED NOT NULL DEFAULT '0' COMMENT '更新时间',
  PRIMARY KEY (`id`) USING BTREE,
  UNIQUE KEY `uk_membership_plan_code` (`tenant_id`,`channel_id`,`plan_code`) USING BTREE,
  UNIQUE KEY `uk_membership_plan_tier` (`tenant_id`,`channel_id`,`tier`) USING BTREE,
  KEY `idx_membership_plan_sale` (`tenant_id`,`channel_id`,`status`,`purchase_enabled`,`tier`) USING BTREE,
  KEY `idx_membership_plan_product` (`tenant_id`,`channel_id`,`product_id`,`product_attr_unique`,`status`) USING BTREE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='租户渠道会籍计划';

