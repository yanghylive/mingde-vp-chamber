  KEY `idx_membership_effect_term` (`tenant_id`,`term_id`,`id`) USING BTREE,
  KEY `idx_membership_effect_context` (`tenant_id`,`order_context_id`,`id`) USING BTREE,
  KEY `idx_membership_effect_event` (`tenant_id`,`event_id`,`id`) USING BTREE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='追加式会籍授予退款与人工调整效果';
